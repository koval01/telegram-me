"""Response models of channel posts."""

from typing import Literal

from pydantic import AnyUrl, BaseModel, HttpUrl


class ParsedAndRaw(BaseModel):
    """Text in two forms: plain `string` and the original `html`."""

    string: str
    html: str


class Duration(BaseModel):
    """Duration of time-based media."""

    formatted: str
    """Human-readable value as shown by Telegram, e.g. `2:30`."""
    raw: int
    """Duration in seconds."""


class MediaItem(BaseModel):
    """Media attachment of a post."""

    url: HttpUrl | None = None
    thumb: HttpUrl | None = None
    waves: str | None = None
    """Encoded waveform of a voice message."""
    duration: Duration | None = None
    type: Literal["image", "video", "voice", "roundvideo", "sticker", "gif"]
    available: bool | None = None
    """False when Telegram does not expose the file (e.g. a too large video)."""


class TextEntities(BaseModel):
    """Formatting entity inside a post text; offsets refer to `Text.string`."""

    offset: int
    length: int
    type: Literal[
        "italic", "bold", "code", "spoiler", "strikethrough",
        "underline", "text_link", "url", "pre", "emoji",
        "animoji", "hashtag",
    ]  # fmt: skip
    language: str | None = None
    url: AnyUrl | None = None


class Text(BaseModel):
    """Post text with optional formatting entities."""

    string: str
    html: str
    entities: list[TextEntities] | None = None


class PollOptions(BaseModel):
    """One answer option of a poll."""

    name: str
    percent: int


class Poll(BaseModel):
    """Poll attached to a post."""

    question: str
    type: str | None = None
    votes: str | None = None
    options: list[PollOptions]


class Inline(BaseModel):
    """Inline keyboard button."""

    title: str
    url: AnyUrl


class Reply(BaseModel):
    """The message this post replies to."""

    cover: AnyUrl | None = None
    name: ParsedAndRaw
    text: ParsedAndRaw
    to_message: int


class PreviewLink(BaseModel):
    """Link preview card generated by Telegram."""

    title: str | None = None
    url: HttpUrl
    site_name: str | None = None
    description: ParsedAndRaw | None = None
    thumb: HttpUrl | None = None


class Reacts(BaseModel):
    """One reaction counter of a post."""

    count: str
    type: Literal["telegram_stars", "emoji", "custom_emoji"]
    emoji: str | None = None
    emoji_id: str | None = None
    emoji_image: HttpUrl | None = None


class ContentPost(BaseModel):
    """Everything a post can contain."""

    text: Text | None = None
    media: list[MediaItem] | None = None
    poll: Poll | None = None
    inline: list[Inline] | None = None
    reply: Reply | None = None
    preview_link: PreviewLink | None = None
    reacts: list[Reacts] | None = None


class Date(BaseModel):
    """Publication time."""

    string: str
    """ISO-8601 timestamp with offset."""
    unix: int


class Footer(BaseModel):
    """Post metadata shown under the message."""

    views: str | None = None
    edited: bool | None = False
    author: ParsedAndRaw | None = None
    date: Date


class Forwarded(BaseModel):
    """Original source of a forwarded post."""

    name: ParsedAndRaw
    """Source channel or user; empty when the sender hides their name."""
    url: HttpUrl | None = None
    author: ParsedAndRaw | None = None
    """Signature shown next to the source, e.g. the bot that posted it."""


class Post(BaseModel):
    """A channel post."""

    id: int
    content: ContentPost
    footer: Footer
    forwarded: Forwarded | None = None
    view: str
