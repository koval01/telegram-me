"""GraphQL object types mirroring the REST models in `telegram_me.schemas`.

Resolvers return the JSON-compatible dicts the REST endpoints serialize (the
same cached, validated data), and fields read them by key through the
schema's default resolver. The classes below only declare the shape: they
are never instantiated. Field names are the REST keys (snake_case), so a
GraphQL result is a subset of the matching REST response.
"""

from enum import StrEnum
from typing import NewType

import strawberry
from strawberry.types.scalar import ScalarDefinition

from telegram_me.telegram.parsing.html import JSONDict

Long = NewType("Long", int)
"""Integer that may exceed 32 bits (Unix timestamps); see `SCALARS`."""

SCALARS: dict[object, ScalarDefinition] = {
    Long: strawberry.scalar(
        name="Long",
        description="Integer that may exceed 32 bits (Unix timestamps).",
        serialize=int,
        parse_value=int,
    )
}


def _object[T](cls: type[T]) -> type[T]:
    """Declare a GraphQL object type described by the class docstring."""
    return strawberry.type(cls, description=cls.__doc__)


def _enum[E: StrEnum](cls: type[E]) -> type[E]:
    """Declare a GraphQL enum described by the class docstring."""
    return strawberry.enum(cls, description=cls.__doc__)


@_enum
class MediaType(StrEnum):
    """Kind of a media attachment."""

    image = "image"
    video = "video"
    voice = "voice"
    roundvideo = "roundvideo"
    sticker = "sticker"
    gif = "gif"


@_enum
class EntityType(StrEnum):
    """Kind of a formatting entity."""

    italic = "italic"
    bold = "bold"
    code = "code"
    spoiler = "spoiler"
    strikethrough = "strikethrough"
    underline = "underline"
    text_link = "text_link"
    url = "url"
    pre = "pre"
    emoji = "emoji"
    animoji = "animoji"
    hashtag = "hashtag"


@_enum
class ReactionType(StrEnum):
    """Kind of a reaction."""

    telegram_stars = "telegram_stars"
    emoji = "emoji"
    custom_emoji = "custom_emoji"


@_enum
class Direction(StrEnum):
    """Load posts newer (`after`) or older (`before`) than a position."""

    after = "after"
    before = "before"


@_object
class ParsedAndRaw:
    """Text in two forms: plain `string` and the original `html`."""

    string: str
    html: str


@_object
class Duration:
    """Duration of time-based media."""

    formatted: str = strawberry.field(
        description="Human-readable value as shown by Telegram, e.g. `2:30`."
    )
    raw: int = strawberry.field(description="Duration in seconds.")


@_object
class MediaItem:
    """Media attachment of a post."""

    url: str | None
    thumb: str | None
    waves: str | None = strawberry.field(description="Encoded waveform of a voice message.")
    duration: Duration | None
    type: MediaType
    available: bool | None = strawberry.field(
        description="False when Telegram does not expose the file (e.g. a too large video)."
    )


@_object
class TextEntity:
    """Formatting entity inside a post text; offsets refer to `string`."""

    offset: int
    length: int
    type: EntityType
    language: str | None
    url: str | None


@_object
class Text:
    """Post text with optional formatting entities."""

    string: str
    html: str
    entities: list[TextEntity] | None


@_object
class PollOption:
    """One answer option of a poll."""

    name: str
    percent: int


@_object
class Poll:
    """Poll attached to a post."""

    question: str
    type: str | None
    votes: str | None
    options: list[PollOption]


@_object
class InlineButton:
    """Inline keyboard button."""

    title: str
    url: str


@_object
class Reply:
    """The message this post replies to."""

    cover: str | None
    name: ParsedAndRaw
    text: ParsedAndRaw
    to_message: int


@_object
class PreviewLink:
    """Link preview card generated by Telegram."""

    title: str | None
    url: str
    site_name: str | None
    description: ParsedAndRaw | None
    thumb: str | None


@_object
class Reaction:
    """One reaction counter of a post."""

    count: str
    type: ReactionType
    emoji: str | None
    emoji_id: str | None
    emoji_image: str | None


@_object
class PostContent:
    """Everything a post can contain."""

    text: Text | None
    media: list[MediaItem] | None
    poll: Poll | None
    inline: list[InlineButton] | None
    reply: Reply | None
    preview_link: PreviewLink | None
    reacts: list[Reaction] | None


@_object
class Date:
    """Publication time."""

    string: str = strawberry.field(description="ISO-8601 timestamp with offset.")
    unix: Long


@_object
class Footer:
    """Post metadata shown under the message."""

    views: str | None
    edited: bool | None
    author: ParsedAndRaw | None
    date: Date


@_object
class Forwarded:
    """Original source of a forwarded post."""

    name: ParsedAndRaw = strawberry.field(
        description="Source channel or user; empty when the sender hides their name."
    )
    url: str | None
    author: ParsedAndRaw | None = strawberry.field(
        description="Signature shown next to the source, e.g. the bot that posted it."
    )


@_object
class Post:
    """A channel post."""

    id: int
    content: PostContent
    footer: Footer
    forwarded: Forwarded | None
    view: str


@_object
class Counters:
    """Channel statistics as formatted by Telegram (e.g. `1.2M`)."""

    subscribers: str
    photos: str | None
    videos: str | None
    files: str | None
    links: str | None


@_object
class Channel:
    """Channel profile shown above the posts."""

    username: str
    title: ParsedAndRaw
    description: ParsedAndRaw | None
    avatar: str | None
    counters: Counters
    labels: list[str] | None = strawberry.field(description="Header labels, e.g. `verified`.")


@_object
class Offset:
    """Pagination cursors: pass them to `more` to load adjacent posts."""

    before: int | None
    after: int | None


@_object
class Meta:
    """Pagination metadata."""

    offset: Offset


@_object
class ChannelContent:
    """Posts of a channel page."""

    posts: list[Post]


@_object
class ChannelBody:
    """Channel page: profile, posts and pagination."""

    channel: Channel
    content: ChannelContent
    meta: Meta


@_object
class More:
    """A batch of posts loaded relative to a position."""

    posts: list[Post]
    meta: Meta


@_object
class PreviewChannel:
    """Channel summary from the `t.me/<channel>` landing page."""

    title: str
    subscribers: str
    description: str | None
    avatar: str | None
    is_verified: bool


@_object
class Preview:
    """Channel preview."""

    username: str = strawberry.field(description="The requested channel username.")
    channel: PreviewChannel | None


@_object
class FeedDuplicate:
    """The same story posted by another channel, collapsed into a feed post."""

    channel: str | None
    id: int


@_object
class FeedTopic:
    """A subject a feed post shares with other posts of the feed."""

    id: int
    keywords: list[str]


def _score(parent: strawberry.Parent[JSONDict]) -> float:
    score: float = parent["_score"]
    return score


def _duplicates(parent: strawberry.Parent[JSONDict]) -> list[JSONDict] | None:
    duplicates: list[JSONDict] | None = parent.get("_duplicates")
    return duplicates


def _topic(parent: strawberry.Parent[JSONDict]) -> JSONDict | None:
    topic: JSONDict | None = parent.get("_topic")
    return topic


@_object
class FeedPost(Post):
    """A feed post with its channel and ranking data."""

    channel: Channel
    score = strawberry.field(
        resolver=_score,
        description="Ranking score (`_score` in the REST feed).",
    )
    duplicates = strawberry.field(
        resolver=_duplicates,
        graphql_type=list[FeedDuplicate] | None,
        description="Reposts of this story by other channels (`_duplicates`).",
    )
    topic = strawberry.field(
        resolver=_topic,
        graphql_type=FeedTopic | None,
        description="Subject shared with other feed posts (`_topic`).",
    )
